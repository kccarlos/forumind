#!/usr/bin/env bash
# Regenerates ForumindShare/PageFactsProbe.js, the share extension's Safari
# preprocessing script, from the Swift probe (PageFactsProbe.expression) and
# the recognizers' declared keys. Run it after changing a recognizer's
# `factKeys` or the probe; SharedProbeScriptTests fails when the shipped file
# is out of date. Compiles only the extension's recognition sources.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

cat >"$work/main.swift" <<'SWIFT'
import Foundation

let expression = PageFactsProbe.expression(keys: SiteRecognizers.factKeys)
print("""
// Generated by scripts/generate-share-probe.sh from PageFactsProbe.swift and
// the recognizers' declared keys; do not edit. Safari runs this in the shared
// page before the share sheet opens (NSExtensionJavaScriptPreprocessingFile).
// The result is a property list: null and undefined values are dropped.
var PageFactsProbe = function () {};

PageFactsProbe.prototype = {
  run: function (arguments) {
    var result;
    try {
      result = (\(expression))();
    } catch (error) {
      result = { url: String(window.location.href) };
    }
    arguments.completionFunction(result);
  },

  finalize: function (arguments) {}
};

var ExtensionPreprocessingJS = new PageFactsProbe();
""")
SWIFT

swiftc -o "$work/gen" -module-name Gen \
  Forumind/ForumSite.swift Forumind/Sites/Recognition/*.swift "$work/main.swift" 2>"$work/err" ||
  { cat "$work/err" >&2; exit 1; }
"$work/gen" >ForumindShare/PageFactsProbe.js
